/**
 * Raksara SEO helpers for SvelteKit.
 * Generates JSON-LD structured data and social meta tag objects.
 */

import type { SiteConfig, Post, PortfolioItem, Page } from './types';
import { resolveAdsenseConfig } from './advertising.js';

export type JsonLdObject = Record<string, unknown>;

export interface PageMeta {
  title: string;
  description: string;
  url: string;
  image?: string;
  type?: 'website' | 'article';
  author?: string;
  date?: string;
  tags?: string[];
  jsonLd?: JsonLdObject;
}

type SiteSeoConfig = {
  site_name?: string;
  alternate_names?: string[];
  author_path?: string;
};

/** Serialize JSON-LD safely for injection into <script type="application/ld+json"> */
export function serializeJsonLd(value: unknown): string {
  return JSON.stringify(value)
    .replace(/</g, '\\u003c')
    .replace(/>/g, '\\u003e')
    .replace(/&/g, '\\u0026')
    .replace(/\u2028/g, '\\u2028')
    .replace(/\u2029/g, '\\u2029');
}

function resolveUrl(path: string, siteUrl?: string): string {
  const base = (siteUrl ?? '').replace(/\/$/, '');
  return `${base}${path.startsWith('/') ? path : '/' + path}`;
}

function getSiteSeoConfig(config: SiteConfig): SiteSeoConfig {
  const raw = config as SiteConfig & { seo?: SiteSeoConfig };
  return raw.seo ?? {};
}

/** Resolve brand/site name from config (SEO site name takes priority). */
function brandName(config: SiteConfig): string {
  const seo = getSiteSeoConfig(config);
  return seo.site_name ?? config.hero_title ?? config.title ?? '';
}

/** Search engines truncate titles at roughly 60 characters. */
export const MAX_TITLE_LENGTH = 60;
/** Search engines truncate descriptions at roughly 160 characters. */
export const MAX_DESCRIPTION_LENGTH = 160;

/**
 * Join a page title with the brand ("Title · Brand"), dropping the brand when the
 * combined title would be truncated in search results.
 */
export function composeTitle(title: string, brand: string, maxLength = MAX_TITLE_LENGTH): string {
  const cleanTitle = title.trim();
  const cleanBrand = brand.trim();
  if (!cleanBrand) return cleanTitle;
  if (!cleanTitle) return cleanBrand;
  const combined = `${cleanTitle} · ${cleanBrand}`;
  if (combined.length > maxLength) return cleanTitle;
  return combined;
}

/** Shorten a description to fit a search snippet, cutting at a word boundary. */
export function truncateDescription(text: string, maxLength = MAX_DESCRIPTION_LENGTH): string {
  const clean = text.replace(/\s+/g, ' ').trim();
  if (clean.length <= maxLength) return clean;
  const hardCut = clean.slice(0, maxLength - 1);
  const lastSpace = hardCut.lastIndexOf(' ');
  const wordCut = lastSpace > maxLength * 0.6 ? hardCut.slice(0, lastSpace) : hardCut;
  return `${wordCut.replace(/[\s,;:.\-–—]+$/, '')}…`;
}

type OgDefaults = NonNullable<SiteConfig['og_defaults']>;

/** Built-in OG cards generated by scripts/og-images.js for every site. */
const BUILT_IN_OG_DEFAULTS = {
  site: '/og/defaults/pages-landscape.jpg',
  blog: '/og/defaults/blog-landscape.jpg',
  portfolio: '/og/defaults/portfolio-landscape.jpg',
  profile: '/og/defaults/profile-landscape.jpg',
} as const;

function toAbsoluteUrl(value: string, root: string): string {
  if (/^https?:\/\//i.test(value)) return value;
  return `${root}/${value.replace(/^\/+/, '')}`;
}

/**
 * Pick the default social-share image for a path. Config `og_defaults` win;
 * otherwise the built-in generated cards are used so every page has an image.
 */
export function resolveDefaultOgImage(path: string, root: string, ogDefaults?: OgDefaults): string {
  const pick = (key: keyof typeof BUILT_IN_OG_DEFAULTS): string => {
    const configured = ogDefaults?.[key];
    if (configured) return toAbsoluteUrl(configured, root);
    return toAbsoluteUrl(BUILT_IN_OG_DEFAULTS[key], root);
  };
  const siteDefault = pick('site');
  if (path.startsWith('/blog')) return pick('blog');
  if (path.startsWith('/portfolio')) return pick('portfolio');
  const isProfilePath = /^\/(profile|about)(\/|$)/.test(path);
  if (isProfilePath) return pick('profile');
  return siteDefault;
}

/** Build PageMeta for a blog post or portfolio item. */
export function buildPostMeta(
  post: Post | PortfolioItem,
  config: SiteConfig,
  slug: string
): PageMeta {
  const isPost = post.section === 'blog';
  const siteUrl = config.site_url ?? config.url;
  const root = (siteUrl ?? '').replace(/\/+$/, '');
  const url = resolveUrl(isPost ? `/blog/post/${slug}/` : `/portfolio/${slug}/`, siteUrl);
  const image = post.cover ? resolveUrl(post.cover, siteUrl) : undefined;

  const authorName = (post as Post & { author?: string }).author ?? config.author ?? '';
  const updatedDate = (post as Post & { updated?: string; modified?: string }).updated
    ?? (post as Post & { updated?: string; modified?: string }).modified
    ?? post.date;
  const articleSchemaType = isPost && post.schema_type === 'TechArticle'
    ? 'TechArticle'
    : 'BlogPosting';
  // Never replace missing page-specific copy with the site's generic description.
  const description = post.summary?.trim() || `Read ${post.title} on ${brandName(config)}.`;

  const jsonLd: JsonLdObject = {
    '@context': 'https://schema.org',
    '@type': isPost ? articleSchemaType : ((post as PortfolioItem).github ? 'SoftwareSourceCode' : 'CreativeWork'),
    ...(isPost ? { headline: post.title } : { name: post.title }),
    description,
    author: [
      {
        '@type': 'Person',
        ...(root ? { '@id': `${root}/#author` } : {}),
        name: authorName,
      },
    ],
    datePublished: post.date,
    dateModified: updatedDate,
    mainEntityOfPage: {
      '@type': 'WebPage',
      '@id': url,
    },
    ...(root ? { isPartOf: { '@id': `${root}/#website` } } : {}),
    url,
    ...(!isPost && (post as PortfolioItem).github ? { codeRepository: (post as PortfolioItem).github } : {}),
    ...(image ? { image: [image] } : {}),
    ...(post.tags?.length ? { keywords: post.tags.join(', ') } : {}),
  };

  return {
    title: `${post.title} — ${brandName(config)}`,
    description,
    url,
    image,
    type: 'article',
    author: config.author,
    date: post.date,
    tags: post.tags,
    jsonLd,
  };
}

/** Build PageMeta for a generic / index page. */
export function buildPageMeta(
  opts: {
    title?: string;
    description?: string;
    path?: string;
    image?: string;
  },
  config: SiteConfig
): PageMeta {
  const brand = brandName(config);
  const title = opts.title ? `${opts.title} — ${brand}` : brand;
  const description = opts.description?.trim()
    || (opts.title ? `Explore ${opts.title} on ${brand}.` : config.description ?? '');
  const url = resolveUrl(opts.path ?? '/', config.site_url ?? config.url);
  return {
    title,
    description,
    url,
    image: opts.image,
    type: 'website',
  };
}

/** Build WebSite JSON-LD schema for the homepage. */
export function buildWebSiteSchema(config: SiteConfig, siteUrl: string): JsonLdObject {
  const root = siteUrl.replace(/\/+$/, '');
  const seo = getSiteSeoConfig(config);
  const name = seo.site_name ?? config.hero_title ?? config.title ?? '';
  const alternateNames = Array.isArray(seo.alternate_names)
    ? Array.from(new Set(seo.alternate_names.map((value) => String(value).trim()).filter((value) => value && value !== name)))
    : [];

  return {
    '@context': 'https://schema.org',
    '@type': 'WebSite',
    '@id': `${root}/#website`,
    name,
    ...(alternateNames.length === 1 ? { alternateName: alternateNames[0] } : {}),
    ...(alternateNames.length > 1 ? { alternateName: alternateNames } : {}),
    ...(config.description || config.hero_subtitle
      ? { description: config.description ?? config.hero_subtitle }
      : {}),
    url: `${root}/`,
    ...(config.author ? { creator: { '@id': `${root}/#author` } } : {}),
  };
}

/** Collect absolute profile URLs from site config and the profile page. */
function collectSameAs(config: SiteConfig, profile?: Page | null): string[] {
  const candidates: unknown[] = [
    ...Object.values(config.social ?? {}),
    profile?.github,
    profile?.linkedin,
    profile?.medium,
  ];
  const urls = candidates
    .filter((value): value is string => typeof value === 'string')
    .map((value) => value.trim())
    .filter((value) => /^https?:\/\//i.test(value));
  return Array.from(new Set(urls));
}

/**
 * Build Person JSON-LD schema for the site author. Returns null if no author configured.
 * The optional profile page supplies the full name, role, and social profile links.
 */
export function buildPersonSchema(
  config: SiteConfig,
  siteUrl: string,
  profile?: Page | null
): JsonLdObject | null {
  const author = config.author;
  if (!author) return null;
  const root = siteUrl.replace(/\/+$/, '');
  const seo = getSiteSeoConfig(config);
  const authorPath = String(seo.author_path ?? '/profile/').trim() || '/profile/';
  const sameAs = collectSameAs(config, profile);
  const fullName = profile?.title?.trim() || author;
  const alternateName = fullName === author ? undefined : author;
  const jobTitle = profile?.role?.trim();
  return {
    '@context': 'https://schema.org',
    '@type': 'Person',
    '@id': `${root}/#author`,
    name: fullName,
    ...(alternateName ? { alternateName } : {}),
    ...(jobTitle ? { jobTitle } : {}),
    url: resolveUrl(authorPath, root),
    ...(sameAs.length ? { sameAs } : {}),
  };
}

export type WebPageKind = 'WebPage' | 'AboutPage' | 'ContactPage' | 'CollectionPage' | 'ProfilePage';

/** Build a generic page JSON-LD object that points back to the site and author. */
export function buildWebPageSchema(
  opts: {
    type: WebPageKind;
    name: string;
    description: string;
    path: string;
    /** Embed the author as the page's main entity (used by ProfilePage). */
    mainEntity?: JsonLdObject | null;
  },
  siteUrl: string
): JsonLdObject {
  const root = siteUrl.replace(/\/+$/, '');
  const url = resolveUrl(opts.path, root);
  return {
    '@context': 'https://schema.org',
    '@type': opts.type,
    '@id': `${url}#webpage`,
    name: opts.name,
    description: opts.description,
    url,
    isPartOf: { '@id': `${root}/#website` },
    ...(opts.mainEntity ? { mainEntity: opts.mainEntity } : {}),
  };
}

/** Pick the most specific schema.org page type for a standalone page slug. */
export function pageKindForSlug(slug: string): WebPageKind {
  if (slug === 'about') return 'AboutPage';
  if (slug === 'contact') return 'ContactPage';
  return 'WebPage';
}

/** Build BreadcrumbList JSON-LD schema. Items ordered from root to current page. */
export function buildBreadcrumbSchema(
  items: Array<{ name: string; url?: string }>,
  siteUrl: string
): JsonLdObject {
  const root = siteUrl.replace(/\/+$/, '');
  return {
    '@context': 'https://schema.org',
    '@type': 'BreadcrumbList',
    itemListElement: items.map((item, i) => ({
      '@type': 'ListItem',
      position: i + 1,
      name: item.name,
      ...(item.url
        ? { item: `${root}${item.url.startsWith('/') ? item.url : '/' + item.url}` }
        : {}),
    })),
  };
}

/** Legacy utility: publisher ID for an enabled optional site configuration. */
export function getAdsenseId(config: SiteConfig): string {
  return resolveAdsenseConfig(config).publisherId;
}

/** Resolve effective Giscus config from either config.comments or config.giscus. */
export function getGiscusConfig(config: SiteConfig): {
  enabled: boolean;
  repo: string;
  repoId: string;
  category: string;
  categoryId: string;
  pages: string[];
} | null {
  const comments = config.comments;
  const giscus = config.giscus;
  if (comments?.enabled && comments.repo) {
    const raw = comments as typeof comments & { repo_id?: string; category_id?: string };
    return {
      enabled: true,
      repo: comments.repo,
      repoId: comments.repoId ?? raw.repo_id ?? '',
      category: comments.category,
      categoryId: comments.categoryId ?? raw.category_id ?? '',
      pages: comments.pages ?? ['blog', 'portfolio'],
    };
  }
  if (giscus?.repo) {
    const raw = giscus as typeof giscus & { repo_id?: string; category_id?: string };
    return {
      enabled: true,
      repo: giscus.repo,
      repoId: giscus.repoId ?? raw.repo_id ?? '',
      category: giscus.category,
      categoryId: giscus.categoryId ?? raw.category_id ?? '',
      pages: ['blog', 'portfolio'],
    };
  }
  return null;
}

/** Whether to show Giscus on a given page type, respecting frontmatter override. */
export function shouldShowGiscus(
  config: SiteConfig,
  pageType: string,
  commentsEnabled?: boolean
): boolean {
  const gcfg = getGiscusConfig(config);
  if (!gcfg) return false;
  if (commentsEnabled === false) return false;
  if (commentsEnabled === true) return true;
  return gcfg.pages.includes(pageType);
}
